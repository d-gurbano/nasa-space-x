const times = (f: number) => `${Math.round(f)}&times;`;

function impactHtml(s: ImpactSummary): string {
  if (!s.top.length && !s.today) return '';
  const cards = s.top.map(
    (g) => `<li class="ab-gain">
      <p class="kicker"><a href="#/object/${esc(g.slug)}">${esc(g.name)}</a></p>
      <p class="ab-gain-num"><small>about</small> ${times(g.factor)}</p>
      <p class="ab-gain-what">smaller 3σ position uncertainty one year ahead, in the at-discovery scenario (first 7 days of observations).</p>
      <p class="hint">${millionKm(g.kmBefore)} down to ${millionKm(g.kmAfter)}, with ${plural(g.positions, 'SPHEREx precovery position')}.</p>
    </li>`,
  );
  if (s.today) {
    const [lo, hi] = s.today;
    cards.push(`<li class="ab-gain ab-gain-now">
      <p class="kicker">Today</p>
      <p class="ab-gain-num">${lo === hi ? hi : `${lo} to ${hi}`}%</p>
      <p class="ab-gain-what">reduction for the same objects with today’s observed arcs.</p>
      <p class="hint">After weeks to a year of follow-up, precovery positions change the orbit little.</p>
    </li>`);
  }
  const rest = s.rest ? ` For the other finds the factor was ×${s.rest[0]} to ×${s.rest[1]} (below 1 means the formal uncertainty grew)${s.weak ? `; for ${s.weak} the short-arc fit was too weak to sample` : ''}.` : '';
  return `<ul class="ab-gains">${cards.join('')}</ul>
    <p class="ab-method">${chip('Computed')}<span class="hint">kete least-squares fits of the MPC observations, with and without the SPHEREx positions; 3σ largest-axis uncertainty from covariance clones, gravity only.${rest} Nothing was submitted to the Minor Planet Center.</span></p>`;
}

// step 1 plays the day-by-day photos as a flipbook, step 2 shows the stack, step 3 the orbit moving
function howItWorks(body: HTMLElement, base: string, row?: IndexObject): () => void {
  let timer = 0;
  let stopOrbit = () => {};
  const days = body.querySelector('.ab-days') as HTMLElement;
  const stack = body.querySelector('.ab-stack-box') as HTMLElement;
  const canvas = body.querySelector('.ab-orbit-box canvas') as HTMLCanvasElement;
  let alive = true;
  getJson<ObjectPage>(base + YH5 + 'object.json').then((o) => {
    if (!alive) return;
    const d = o.spherex.days;
    days.innerHTML = `<img alt="" /><span class="ab-tag mono"></span><span class="ab-dots">${d.map((x, k) => `<button aria-label="${esc(plainDate(x.iso))}" data-k="${k}"></button>`).join('')}</span>`;
    const img = days.querySelector('img') as HTMLImageElement;
    const tag = days.querySelector('.ab-tag') as HTMLElement;
    const dots = [...days.querySelectorAll<HTMLButtonElement>('button')];
    let k = 0;
    const show = (i: number) => {
      k = (i + d.length) % d.length;
      img.src = base + YH5 + d[k].png;
      const snr = d[k].snr;
      tag.textContent = `${d[k].iso}  ${snr === null ? 'no signal' : 'S/N ' + snr.toFixed(1)}`;
      dots.forEach((b, j) => b.toggleAttribute('data-on', j === k));
    };
    d.forEach((x) => (new Image().src = base + YH5 + x.png));
    dots.forEach((b, j) => b.addEventListener('click', () => { clearInterval(timer); show(j); }));
    show(0);
    if (!matchMedia('(prefers-reduced-motion: reduce)').matches) timer = window.setInterval(() => show(k + 1), 650);

    const s = o.spherex.stack;
    (stack.querySelector('img') as HTMLImageElement).src = base + YH5 + s.png;
    (stack.querySelector('.ab-tag') as HTMLElement).textContent = `${s.n_frames} images stacked · S/N ${s.snr?.toFixed(1) ?? 'n/a'}`;
    (body.querySelector('.ab-days-text') as HTMLElement).textContent =
      // the same count as the object's own page and the results list (index.json)
      row && (daysBefore(row) ?? 0) > 0
        ? `SPHEREx imaged it on ${d.length} nights, the first ${plural(Math.round(daysBefore(row)!), 'day')} before ${beforeWhat(row)}. On any single night it is at or below the noise.`
        : `SPHEREx imaged it on ${d.length} nights. On any single night it is at or below the noise.`;
    if (o.orbit) stopOrbit = animateOrbits([{ canvas, el: o.orbit, mjd0: mjdFromIso(o.story.discovered_iso) - 120, color: '#f2b544' }]);
  }).catch(() => body.querySelector('.ab-how')?.closest('.sec')?.remove());
  return () => {
    alive = false;
    clearInterval(timer);
    stopOrbit();
  };
}

