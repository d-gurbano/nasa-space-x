"""Orbits for the "Does it work?" cards: JPL SBDB elements of every benchmark case.

Reads MAIN/data/results/c2-engine/sbdb/<number>.json for the bench-* and b2-* cases and writes
src/views/visuals/bench-orbits.ts ({number: {a, e, i, node, peri, M, epoch_mjd}}).

Run:  python3 -I web/scripts/bench-visuals.py MAIN/data/results/c2-engine web
"""
import json
import sys
from pathlib import Path

src, web = Path(sys.argv[1]), Path(sys.argv[2])
keys = sorted({d.name.split('-', 1)[1].removesuffix('-decoy') for d in (src / 'stamps').iterdir() if d.name.startswith(('bench-', 'b2-'))})
orbits = {}
for key in keys:
    sb = src / 'sbdb' / f'{key}.json'
    if not sb.exists():
        continue
    o = json.loads(sb.read_text())['orbit']
    el = {e['name']: float(e['value']) for e in o['elements']}
    if el.get('e', 1) < 1 and 'a' in el:
        orbits[key] = {
            'a': round(el['a'], 6), 'e': round(el['e'], 6), 'i': round(el['i'], 4), 'node': round(el['om'], 4),
            'peri': round(el['w'], 4), 'M': round(el['ma'], 4), 'epoch_mjd': round(float(o['epoch']) - 2400000.5, 3),
        }
(web / 'src/views/visuals').mkdir(parents=True, exist_ok=True)
ts = ('// Generated by web/scripts/bench-visuals.py from JPL SBDB (MAIN/data/results/c2-engine/sbdb). Do not edit.\n'
      "import type { Elements } from '../../lib/kepler';\n\n"
      'export const BENCH_ORBITS: Record<string, Elements> = ' + json.dumps(orbits, indent=1) + ';\n')
(web / 'src/views/visuals/bench-orbits.ts').write_text(ts)
print(len(orbits), 'orbits')
