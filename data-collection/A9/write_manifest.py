"""A9: folder-wide manifest (filename, url, bytes, sha256, date). URLs from sub-manifests where known."""
import os,csv,hashlib,datetime
R='data/09-people'; urls={}
for m in [f'{R}/media/manifest.csv',f'{R}/names/wgsbn_manifest.csv']:
    for r in csv.DictReader(open(m)): urls[os.path.basename(r['filename'])]=r['url']
out=[]
for dp,_,fs in os.walk(R):
    for f in sorted(fs):
        p=os.path.join(dp,f); rel=os.path.relpath(p,R)
        if rel=='manifest.csv': continue
        b=open(p,'rb').read()
        out.append(dict(filename=rel,url=urls.get(f,'generated by code/A9 (see docs/SOURCES.md)'),bytes=len(b),sha256=hashlib.sha256(b).hexdigest(),date=datetime.date.today().isoformat()))
with open(f'{R}/manifest.csv','w',newline='') as fh:
    w=csv.DictWriter(fh,fieldnames=['filename','url','bytes','sha256','date']); w.writeheader(); w.writerows(out)
print(len(out),sum(o['bytes'] for o in out))
